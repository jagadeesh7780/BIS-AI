// Clean exact match text normalizer
function normalizeText(text) {
  if (!text) return "";
  return text.trim().replace(/\s+/g, " ");
}

export function translatePhrase(text, targetLang) {
  if (!text || targetLang === "en") return text;
  const normalized = normalizeText(text);
  if (!normalized) return text;

  // 1. Direct exact match
  if (DICTIONARY[normalized] && DICTIONARY[normalized][targetLang]) {
    return DICTIONARY[normalized][targetLang];
  }

  // 2. Case-insensitive exact lookup
  const lower = normalized.toLowerCase();
  for (const [key, trans] of Object.entries(DICTIONARY)) {
    if (key.toLowerCase() === lower && trans[targetLang]) {
      return trans[targetLang];
    }
  }

  return text;
}

export function translateNodeTree(rootNode, targetLang) {
  if (!rootNode) return;
  const isEn = targetLang === "en";

  const walker = document.createTreeWalker(
    rootNode,
    NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
    null
  );

  let currentNode = walker.nextNode();
  while (currentNode) {
    if (currentNode.nodeType === Node.TEXT_NODE) {
      const parent = currentNode.parentNode;
      if (parent && !["SCRIPT", "STYLE", "NOSCRIPT", "CODE", "PRE"].includes(parent.nodeName)) {
        if (currentNode.__origText === undefined) {
          currentNode.__origText = currentNode.nodeValue;
        }

        if (isEn) {
          if (currentNode.__origText !== undefined && currentNode.nodeValue !== currentNode.__origText) {
            currentNode.nodeValue = currentNode.__origText;
          }
        } else {
          const raw = currentNode.__origText || currentNode.nodeValue;
          const translated = translatePhrase(raw, targetLang);
          if (translated && translated !== currentNode.nodeValue) {
            currentNode.nodeValue = translated;
          }
        }
      }
    } else if (currentNode.nodeType === Node.ELEMENT_NODE) {
      const el = currentNode;
      if (el.hasAttribute("placeholder")) {
        if (el.__origPlaceholder === undefined) {
          el.__origPlaceholder = el.getAttribute("placeholder");
        }
        if (isEn) {
          el.setAttribute("placeholder", el.__origPlaceholder || "");
        } else {
          const trans = translatePhrase(el.__origPlaceholder, targetLang);
          el.setAttribute("placeholder", trans);
        }
      }
      if (el.hasAttribute("title")) {
        if (el.__origTitle === undefined) {
          el.__origTitle = el.getAttribute("title");
        }
        if (isEn) {
          el.setAttribute("title", el.__origTitle || "");
        } else {
          const trans = translatePhrase(el.__origTitle, targetLang);
          el.setAttribute("title", trans);
        }
      }
    }
    currentNode = walker.nextNode();
  }
}
