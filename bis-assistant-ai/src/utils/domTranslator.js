// Auto-generate reverse map for bidirectional translation:
// any translated string in ANY language maps back to its canonical English key!
export const REVERSE_MAP = {};
for (const [canonicalKey, translations] of Object.entries(DICTIONARY)) {
  for (const [lang, val] of Object.entries(translations)) {
    if (val && typeof val === "string") {
      REVERSE_MAP[val.trim().toLowerCase()] = canonicalKey;
    }
  }
}

export function translatePhrase(text, targetLang) {
  if (!text || !targetLang) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Identify canonical English key
  let canonicalKey = null;
  if (DICTIONARY[trimmed]) {
    canonicalKey = trimmed;
  } else if (REVERSE_MAP[trimmed.toLowerCase()]) {
    canonicalKey = REVERSE_MAP[trimmed.toLowerCase()];
  } else {
    const lower = trimmed.toLowerCase();
    for (const key of Object.keys(DICTIONARY)) {
      if (key.toLowerCase() === lower) {
        canonicalKey = key;
        break;
      }
    }
  }

  // If target is English, return canonical key (or original text if not found)
  if (targetLang === "en") {
    return canonicalKey || text;
  }

  // If target is another language and we have a canonical key, translate it
  if (canonicalKey && DICTIONARY[canonicalKey] && DICTIONARY[canonicalKey][targetLang]) {
    return DICTIONARY[canonicalKey][targetLang];
  }

  return text;
}

export function translateNodeTree(rootNode, targetLang) {
  if (!rootNode) return;
  const isEn = targetLang === "en";

  const walker = document.createTreeWalker(
    rootNode,
    NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
    null
  );

  let currentNode = walker.nextNode();
  while (currentNode) {
    if (currentNode.nodeType === Node.TEXT_NODE) {
      const parent = currentNode.parentNode;
      if (parent && !["SCRIPT", "STYLE", "NOSCRIPT", "CODE", "PRE"].includes(parent.nodeName)) {
        const val = currentNode.nodeValue;
        if (val && val.trim()) {
          const trans = translatePhrase(val, targetLang);
          if (trans && trans !== val) {
            currentNode.nodeValue = trans;
          }
        }
      }
    } else if (currentNode.nodeType === Node.ELEMENT_NODE) {
      const el = currentNode;
      if (el.hasAttribute("placeholder")) {
        const ph = el.getAttribute("placeholder");
        if (ph && ph.trim()) {
          const trans = translatePhrase(ph, targetLang);
          if (trans && trans !== ph) {
            el.setAttribute("placeholder", trans);
          }
        }
      }
      if (el.hasAttribute("title")) {
        const tt = el.getAttribute("title");
        if (tt && tt.trim()) {
          const trans = translatePhrase(tt, targetLang);
          if (trans && trans !== tt) {
            el.setAttribute("title", trans);
          }
        }
      }
    }
    currentNode = walker.nextNode();
  }
}
